    # ------------------------------------------------------------------ 5. maths
    @staticmethod
    def blokkok(szoveg: str) -> list[list[dict]]:
        """The derivation blocks (`aligned` environments) of a note, as the lines the editor sends to the checker."""
        ki, akt = [], None
        for n, sor in enumerate(szoveg.splitlines(), 1):
            if sor.strip().startswith("\\begin{aligned}"):
                akt = []
            elif sor.strip().startswith("\\end{aligned}") and akt is not None:
                ki.append(akt)
                akt = None
            elif akt is not None:
                akt.append({"sor": n, "szoveg": sor})
        return ki

