class DemoCore:
    """A demo workspace generated by the launcher and a real core thread on it (product layout)."""

    def __init__(self, tmp: str):
        self.root, self.home = termek_telepites(tmp)
        self.alap = config.load({"MOS_ROOT": str(self.root), "HOME": str(self.home), "MOS_SETTINGS": ""}, munkater=False)
        self.v = Path(indito.muvelet({"muvelet": "demo"}, self.alap)["munkater"]["vault"])
        self.cfg = termek_cfg(self.root, self.home, self.v, MOS_RUNTIME=str(VALODI.path("runtime")), MOS_LLVM=str(VALODI.path("llvm")),
                              MOS_SDK=str(VALODI.path("sdk")), MOS_MODULOK=str(REPO / "modulok"))
        r, w = os.pipe()
        self.stdin_w, self.stdin_r = os.fdopen(w, "wb"), os.fdopen(r, "rb")
        ki = _Kimenet()
        self.szal = threading.Thread(target=server.start, args=(self.cfg,), kwargs={"stdin": self.stdin_r, "out": ki, "start_delay": 0},
                                     daemon=True)
        self.szal.start()
        if not ki.jel.wait(15):
            raise RuntimeError("the core did not start")
        self.port = json.loads(ki.sorok[0])["port"]

    def k(self, method, path, body=None):
        c = http.client.HTTPConnection("127.0.0.1", self.port, timeout=120)
        c.request(method, path, body=json.dumps(body) if body is not None else None,
                  headers={"Host": f"127.0.0.1:{self.port}", "X-Manifold": API_TITOK, "Content-Type": "application/json"})
        r = c.getresponse()
        t = r.read()
        return r.status, (json.loads(t) if t and r.getheader("Content-Type", "").startswith("application/json") else t)

    def var_index(self):
        assert var_ra(lambda: self.k("GET", "/api/vault/index")[1].get("kesz"), 60)

    def leall(self):
        if not self.stdin_w.closed:
            self.stdin_w.close()
        self.szal.join(30)
        self.stdin_r.close()


